"""Leakage-safe training for the registered SOH baseline models."""

from __future__ import annotations

import json
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Literal, cast

import numpy as np
import pandas as pd
from sklearn.base import RegressorMixin  # type: ignore[import-untyped]
from sklearn.ensemble import (  # type: ignore[import-untyped]
    HistGradientBoostingRegressor,
    RandomForestRegressor,
)
from sklearn.linear_model import LinearRegression  # type: ignore[import-untyped]
from sklearn.pipeline import Pipeline  # type: ignore[import-untyped]
from sklearn.preprocessing import StandardScaler  # type: ignore[import-untyped]

from battery_health.data.split import SplitManifest, validate_split_manifest

TARGET_COLUMN = "soh"
SUPPORTED_MODELS = (
    "linear_regression",
    "random_forest",
    "histogram_gradient_boosting",
)


class BaselineTrainingError(ValueError):
    """Raised when a baseline run violates its data or model contract."""


@dataclass(frozen=True)
class BaselineTrainingResult:
    """Portable artifacts generated by one baseline run."""

    predictions_path: Path
    run_metadata_path: Path


def _linear_regression(_: int) -> RegressorMixin:
    return LinearRegression()


def _random_forest(random_seed: int) -> RegressorMixin:
    return RandomForestRegressor(
        n_estimators=100,
        random_state=random_seed,
        n_jobs=1,
    )


def _histogram_gradient_boosting(random_seed: int) -> RegressorMixin:
    return HistGradientBoostingRegressor(random_state=random_seed)


MODEL_BUILDERS: dict[str, Callable[[int], RegressorMixin]] = {
    "linear_regression": _linear_regression,
    "random_forest": _random_forest,
    "histogram_gradient_boosting": _histogram_gradient_boosting,
}


def _read_labelled_data(data_path: Path) -> pd.DataFrame:
    try:
        frame = pd.read_csv(data_path)
    except (OSError, pd.errors.ParserError) as error:
        raise BaselineTrainingError(f"Unable to read labelled data: {data_path.name}") from error
    if frame.empty:
        raise BaselineTrainingError("Labelled data is empty")
    return frame


def _validate_contract(frame: pd.DataFrame, feature_columns: tuple[str, ...]) -> None:
    if not feature_columns:
        raise BaselineTrainingError("At least one feature column is required")
    if len(set(feature_columns)) != len(feature_columns):
        raise BaselineTrainingError("Feature columns must be unique")
    if TARGET_COLUMN in feature_columns:
        raise BaselineTrainingError("Target column soh cannot be used as an input feature")

    required = ("cell_id", "cycle_index", TARGET_COLUMN, *feature_columns)
    missing = [column for column in required if column not in frame.columns]
    if missing:
        raise BaselineTrainingError(
            "Labelled data is missing required column(s): " + ", ".join(sorted(set(missing)))
        )


def _validate_manifest_coverage(
    frame: pd.DataFrame,
    manifest: SplitManifest,
    data_scope: Literal["all", "train_validation"],
) -> None:
    validate_split_manifest(manifest)
    data_cells = set(frame["cell_id"].astype(str))
    expected_cells = set(manifest.train_cells) | set(manifest.validation_cells)
    if data_scope == "all":
        expected_cells |= set(manifest.test_cells)
    if data_cells != expected_cells:
        missing_from_manifest = sorted(data_cells - expected_cells)
        missing_from_data = sorted(expected_cells - data_cells)
        details: list[str] = []
        if missing_from_manifest:
            details.append("unassigned data cells: " + ", ".join(missing_from_manifest))
        if missing_from_data:
            details.append("manifest cells absent from data: " + ", ".join(missing_from_data))
        raise BaselineTrainingError(
            "Split manifest does not match labelled data; " + "; ".join(details)
        )
    if data_scope == "train_validation" and data_cells & set(manifest.test_cells):
        raise BaselineTrainingError("Train-validation data scope cannot contain test cells")


def _numeric_matrix(frame: pd.DataFrame, columns: tuple[str, ...]) -> pd.DataFrame:
    numeric = cast(
        pd.DataFrame,
        frame.loc[:, list(columns)].apply(pd.to_numeric, errors="coerce"),
    )
    values = numeric.to_numpy(dtype="float64")
    if not np.isfinite(values).all():
        raise BaselineTrainingError("Feature columns must contain only finite numeric values")
    return numeric


def _numeric_target(frame: pd.DataFrame) -> pd.Series[float]:
    target = pd.to_numeric(frame[TARGET_COLUMN], errors="coerce").astype("float64")
    if not np.isfinite(target.to_numpy()).all():
        raise BaselineTrainingError("SOH target must contain only finite numeric values")
    return target


def _model_parameters(model_name: str, random_seed: int) -> dict[str, Any]:
    if model_name == "random_forest":
        return {"n_estimators": 100, "n_jobs": 1, "random_state": random_seed}
    if model_name == "histogram_gradient_boosting":
        return {"random_state": random_seed}
    return {}


def train_baseline(
    *,
    data_path: Path,
    split_manifest: SplitManifest,
    output_dir: Path,
    model_name: str,
    feature_columns: tuple[str, ...],
    random_seed: int,
    prediction_partition: Literal["validation", "test"] = "test",
    data_scope: Literal["all", "train_validation"] = "all",
) -> BaselineTrainingResult:
    """Fit on train cells and predict one explicitly selected held-out partition."""

    if model_name not in MODEL_BUILDERS:
        raise BaselineTrainingError(
            f"Unsupported model {model_name!r}; expected one of: {', '.join(SUPPORTED_MODELS)}"
        )

    frame = _read_labelled_data(data_path)
    _validate_contract(frame, feature_columns)
    if data_scope == "train_validation" and prediction_partition != "validation":
        raise BaselineTrainingError(
            "Train-validation data scope can only predict the validation partition"
        )
    _validate_manifest_coverage(frame, split_manifest, data_scope)

    cell_ids = frame["cell_id"].astype(str)
    train_rows = frame.loc[cell_ids.isin(split_manifest.train_cells)].copy()
    prediction_cells = (
        split_manifest.validation_cells
        if prediction_partition == "validation"
        else split_manifest.test_cells
    )
    prediction_rows = frame.loc[cell_ids.isin(prediction_cells)].copy()

    train_features = _numeric_matrix(train_rows, feature_columns)
    prediction_features = _numeric_matrix(prediction_rows, feature_columns)
    train_target = _numeric_target(train_rows)
    prediction_target = _numeric_target(prediction_rows)

    pipeline = Pipeline(
        steps=[
            ("preprocess", StandardScaler()),
            ("model", MODEL_BUILDERS[model_name](random_seed)),
        ]
    )
    pipeline.fit(train_features, train_target)
    predicted_soh = np.asarray(pipeline.predict(prediction_features), dtype="float64")
    if not np.isfinite(predicted_soh).all():
        raise BaselineTrainingError("Model produced non-finite SOH predictions")

    scaler = pipeline.named_steps["preprocess"]
    if not isinstance(scaler, StandardScaler) or scaler.mean_ is None:
        raise BaselineTrainingError("Training pipeline did not fit its preprocessor")

    output_dir.mkdir(parents=True, exist_ok=True)
    predictions_path = output_dir / f"{prediction_partition}_predictions.csv"
    run_metadata_path = output_dir / "run_metadata.json"

    predictions = prediction_rows.loc[:, ["cell_id", "cycle_index"]].copy()
    predictions["partition"] = prediction_partition
    predictions["actual_soh"] = prediction_target.to_numpy()
    predictions["predicted_soh"] = predicted_soh
    predictions.to_csv(predictions_path, index=False)

    metadata = {
        "input_file": data_path.name,
        "model_name": model_name,
        "model_parameters": _model_parameters(model_name, random_seed),
        "random_seed": random_seed,
        "feature_columns": list(feature_columns),
        "target_column": TARGET_COLUMN,
        "split_strategy": split_manifest.strategy,
        "split_random_seed": split_manifest.random_seed,
        "preprocessor": "StandardScaler",
        "preprocessing_fit_partition": "train",
        "preprocessing_fit_cells": sorted(split_manifest.train_cells),
        "preprocessing_feature_means": scaler.mean_.tolist(),
        "training_row_count": int(len(train_rows)),
        "prediction_partition": prediction_partition,
        "data_scope": data_scope,
        "prediction_cells": sorted(prediction_cells),
        "prediction_row_count": int(len(prediction_rows)),
    }
    if prediction_partition == "test":
        metadata["test_row_count"] = int(len(prediction_rows))
    run_metadata_path.write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return BaselineTrainingResult(
        predictions_path=predictions_path,
        run_metadata_path=run_metadata_path,
    )
