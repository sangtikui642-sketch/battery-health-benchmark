"""Traceable evaluation of held-out SOH predictions."""

from __future__ import annotations

import json
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

import matplotlib
import numpy as np
import pandas as pd
from numpy.typing import NDArray

from battery_health.data.split import (
    SplitManifest,
    SplitValidationError,
    validate_split_manifest,
)

matplotlib.use("Agg")
from matplotlib import pyplot as plt  # noqa: E402

REQUIRED_COLUMNS = ("cell_id", "cycle_index", "actual_soh", "predicted_soh")
FloatArray = NDArray[np.float64]
EvaluationPartition = Literal["validation", "test"]


class EvaluationError(ValueError):
    """Raised when held-out predictions cannot be evaluated safely."""


@dataclass(frozen=True)
class EvaluationResult:
    """Portable artifacts generated by a successful evaluation."""

    metrics_path: Path
    predictions_path: Path
    plot_path: Path


def _read_predictions(predictions_path: Path) -> pd.DataFrame:
    try:
        frame = pd.read_csv(predictions_path)
    except (OSError, pd.errors.ParserError) as error:
        raise EvaluationError(f"Unable to read predictions: {predictions_path.name}") from error
    missing = [column for column in REQUIRED_COLUMNS if column not in frame.columns]
    if missing:
        raise EvaluationError("Predictions are missing required column(s): " + ", ".join(missing))
    if frame.empty:
        raise EvaluationError("Predictions are empty")
    if frame.duplicated(subset=["cell_id", "cycle_index"]).any():
        raise EvaluationError("Predictions contain duplicate cell_id and cycle_index rows")
    return frame


def _validate_partition_contract(
    frame: pd.DataFrame,
    split_manifest: SplitManifest,
    partition: EvaluationPartition,
) -> None:
    expected_partition_cells = (
        split_manifest.validation_cells if partition == "validation" else split_manifest.test_cells
    )
    if not expected_partition_cells:
        raise EvaluationError(f"Split manifest contains no {partition} cells")
    try:
        validate_split_manifest(split_manifest)
    except SplitValidationError as error:
        raise EvaluationError(f"Invalid split manifest: {error}") from error

    prediction_cells = set(frame["cell_id"].astype(str))
    expected_cells = set(expected_partition_cells)
    if prediction_cells != expected_cells:
        unexpected = sorted(prediction_cells - expected_cells)
        missing = sorted(expected_cells - prediction_cells)
        details: list[str] = []
        if unexpected:
            details.append(f"non-{partition} cells: " + ", ".join(unexpected))
        if missing:
            details.append(f"{partition} cells without predictions: " + ", ".join(missing))
        raise EvaluationError(
            f"Prediction cells do not match the {partition} partition; " + "; ".join(details)
        )

    if "partition" in frame.columns and set(frame["partition"].astype(str)) != {partition}:
        raise EvaluationError(f"Evaluation accepts only rows marked as the {partition} partition")


def _numeric_values(frame: pd.DataFrame) -> tuple[FloatArray, FloatArray]:
    actual = pd.to_numeric(frame["actual_soh"], errors="coerce").to_numpy(dtype="float64")
    predicted = pd.to_numeric(frame["predicted_soh"], errors="coerce").to_numpy(dtype="float64")
    if not np.isfinite(actual).all() or not np.isfinite(predicted).all():
        raise EvaluationError("Actual and predicted SOH must contain only finite numeric values")
    if (actual == 0).any():
        raise EvaluationError("MAPE is undefined when actual SOH is zero")
    return actual, predicted


def _calculate_metrics(actual: FloatArray, predicted: FloatArray) -> dict[str, float]:
    errors = predicted - actual
    mae = float(np.mean(np.abs(errors)))
    rmse = float(np.sqrt(np.mean(np.square(errors))))
    mape = float(np.mean(np.abs(errors / actual)) * 100.0)
    residual_sum = float(np.sum(np.square(errors)))
    centered_sum = float(np.sum(np.square(actual - np.mean(actual))))
    if centered_sum == 0.0:
        r_squared = 1.0 if residual_sum == 0.0 else 0.0
    else:
        r_squared = 1.0 - residual_sum / centered_sum
    metrics = {
        "mae": mae,
        "rmse": rmse,
        "mape": mape,
        "r_squared": r_squared,
    }
    if not all(math.isfinite(value) for value in metrics.values()):
        raise EvaluationError("Evaluation produced a non-finite metric")
    return metrics


def _write_plot(
    *,
    actual: FloatArray,
    predicted: FloatArray,
    plot_path: Path,
    partition: EvaluationPartition,
) -> None:
    lower = float(min(np.min(actual), np.min(predicted)))
    upper = float(max(np.max(actual), np.max(predicted)))
    if lower == upper:
        lower -= 0.01
        upper += 0.01

    figure, axis = plt.subplots(figsize=(6.4, 4.8), dpi=120)
    label = "Validation cycles" if partition == "validation" else "Test cycles"
    axis.scatter(actual, predicted, color="#1769aa", alpha=0.8, label=label)
    axis.plot([lower, upper], [lower, upper], color="#c62828", linestyle="--", label="Ideal")
    axis.set_xlabel("Actual SOH (dimensionless ratio)")
    axis.set_ylabel("Predicted SOH (dimensionless ratio)")
    axis.set_title("Actual versus predicted SOH")
    axis.grid(alpha=0.25)
    axis.legend()
    figure.tight_layout()
    figure.savefig(plot_path, format="png")
    plt.close(figure)


def evaluate_predictions(
    *,
    predictions_path: Path,
    split_manifest: SplitManifest,
    output_dir: Path,
    partition: EvaluationPartition = "test",
) -> EvaluationResult:
    """Validate and evaluate one declared held-out partition, writing metrics last."""

    frame = _read_predictions(predictions_path)
    _validate_partition_contract(frame, split_manifest, partition)
    actual, predicted = _numeric_values(frame)
    metrics = _calculate_metrics(actual, predicted)

    output_dir.mkdir(parents=True, exist_ok=True)
    saved_predictions_path = output_dir / "predictions.csv"
    plot_path = output_dir / "actual_vs_predicted.png"
    metrics_path = output_dir / "metrics.json"

    portable_columns = list(REQUIRED_COLUMNS)
    if "partition" in frame.columns:
        portable_columns.insert(2, "partition")
    portable_predictions = frame.loc[:, portable_columns].copy()
    portable_predictions.to_csv(saved_predictions_path, index=False)
    _write_plot(actual=actual, predicted=predicted, plot_path=plot_path, partition=partition)

    report: dict[str, object] = {
        "schema_version": 1,
        "partition": partition,
        **metrics,
        "sample_count": int(len(frame)),
        "cell_count": int(frame["cell_id"].astype(str).nunique()),
        "target": {"name": "soh", "unit": "dimensionless ratio"},
        "metric_definitions": {
            "mae": {
                "unit": "SOH ratio",
                "definition": "mean(abs(predicted_soh - actual_soh))",
            },
            "rmse": {
                "unit": "SOH ratio",
                "definition": "sqrt(mean((predicted_soh - actual_soh)^2))",
            },
            "mape": {
                "unit": "percent",
                "definition": "mean(abs((predicted_soh - actual_soh) / actual_soh)) * 100",
                "zero_actual_policy": "reject evaluation before metrics are written",
            },
            "r_squared": {
                "unit": "dimensionless",
                "definition": "1 - sum((predicted-actual)^2) / sum((actual-mean(actual))^2)",
                "constant_actual_policy": "1 for exact predictions, otherwise 0",
            },
        },
        "artifacts": {
            "predictions": saved_predictions_path.name,
            "actual_vs_predicted_plot": plot_path.name,
        },
    }
    report[f"{partition}_sample_count"] = int(len(frame))
    report[f"{partition}_cell_count"] = int(frame["cell_id"].astype(str).nunique())
    metrics_path.write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return EvaluationResult(
        metrics_path=metrics_path,
        predictions_path=saved_predictions_path,
        plot_path=plot_path,
    )
