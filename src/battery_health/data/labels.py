"""Traceable state-of-health label generation for normalized cycle data."""

from __future__ import annotations

import json
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

REQUIRED_COLUMNS = ("cell_id", "cycle_index", "capacity_ah")
REFERENCE_CAPACITY_COLUMN = "reference_capacity_ah"
TARGET_DEFINITION = "soh = capacity_ah / reference_capacity_ah"


class SOHLabelError(ValueError):
    """Raised when SOH labels cannot be generated without guessing."""


@dataclass(frozen=True)
class SOHLabelResult:
    """Paths generated by successful SOH label generation."""

    labelled_cycles_path: Path
    metadata_path: Path


def _read_cycles(data_path: Path) -> pd.DataFrame:
    try:
        frame = pd.read_csv(data_path)
    except (OSError, pd.errors.ParserError) as error:
        raise SOHLabelError(f"Unable to read normalized data: {data_path.name}") from error

    missing = [column for column in REQUIRED_COLUMNS if column not in frame.columns]
    if missing:
        raise SOHLabelError("Normalized data is missing required column(s): " + ", ".join(missing))
    if frame.empty:
        raise SOHLabelError("Normalized cycle data is empty")
    return frame


def _validated_capacity(series: pd.Series[Any], *, field_name: str) -> pd.Series[float]:
    numeric = pd.to_numeric(series, errors="coerce").astype("float64")
    invalid = numeric.isna() | ~np.isfinite(numeric) | (numeric <= 0)
    if invalid.any():
        raise SOHLabelError(f"{field_name} must contain only finite positive values")
    return numeric


def _resolve_reference_capacity(
    frame: pd.DataFrame,
    *,
    configured_capacity_ah: float | None,
    configured_source: str | None,
) -> tuple[pd.Series[float], str, str]:
    if configured_capacity_ah is not None:
        if not math.isfinite(configured_capacity_ah) or configured_capacity_ah <= 0:
            raise SOHLabelError("Configured reference capacity must be finite and positive")
        if configured_source is None or not configured_source.strip():
            raise SOHLabelError("Configured reference capacity requires an explicit source")
        reference = pd.Series(configured_capacity_ah, index=frame.index, dtype="float64")
        return reference, configured_source, "configured_constant"

    if REFERENCE_CAPACITY_COLUMN in frame.columns:
        reference = _validated_capacity(
            frame[REFERENCE_CAPACITY_COLUMN],
            field_name=REFERENCE_CAPACITY_COLUMN,
        )
        source = configured_source or f"source_data:{REFERENCE_CAPACITY_COLUMN}"
        return reference, source, "source_data_column"

    raise SOHLabelError(
        "Reference capacity is required in configuration or source data; no value was guessed"
    )


def generate_soh_labels(
    *,
    data_path: Path,
    output_dir: Path,
    reference_capacity_ah: float | None = None,
    reference_capacity_source: str | None = None,
) -> SOHLabelResult:
    """Calculate SOH and persist labelled cycles with reference-capacity provenance."""

    frame = _read_cycles(data_path)
    measured_capacity = _validated_capacity(frame["capacity_ah"], field_name="capacity_ah")
    reference_capacity, source, mode = _resolve_reference_capacity(
        frame,
        configured_capacity_ah=reference_capacity_ah,
        configured_source=reference_capacity_source,
    )

    labelled = frame.copy()
    labelled["capacity_ah"] = measured_capacity
    labelled[REFERENCE_CAPACITY_COLUMN] = reference_capacity
    labelled["reference_capacity_source"] = source
    labelled["soh"] = measured_capacity / reference_capacity

    output_dir.mkdir(parents=True, exist_ok=True)
    labelled_cycles_path = output_dir / "cycles_with_soh.csv"
    metadata_path = output_dir / "soh_metadata.json"

    labelled.to_csv(labelled_cycles_path, index=False)
    metadata = {
        "input_file": data_path.name,
        "target_name": "soh",
        "target_definition": TARGET_DEFINITION,
        "capacity_unit": "Ah",
        "row_count": int(len(labelled)),
        "reference_capacity_source": source,
        "reference_capacity_mode": mode,
    }
    metadata_path.write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return SOHLabelResult(
        labelled_cycles_path=labelled_cycles_path,
        metadata_path=metadata_path,
    )
